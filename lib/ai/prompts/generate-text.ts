export interface GenerateTextInput {
  gradeLevel: string;
  topic: string;
  genre: string;
  approxWordCount: number;
  difficulty: string;
  purposeSkillName: string;
}

/**
 * Role: כותב/ת תוכן חינוכי ומורה לקריאה, יוצר/ת יחד טקסט ושאלות הבנה.
 * Context: מורה מבקש/ת טקסט חדש לתרגול קריאה עבור כיתה מסוימת, עם מטרת תרגול.
 * Input: שכבת גיל, נושא, סוג טקסט, אורך משוער, רמת קושי, מיומנות מטרה.
 * Rules: הטקסט מקורי, מתאים לגיל, ללא תוכן לא הולם. השאלות מבוססות אך ורק
 *        על הטקסט שנכתב (לא ידע חיצוני). לפחות שאלה אחת מכל סוג נדרש.
 * Output schema: generateTextWithQuestionsOutputSchema.
 * Safety constraints: תוכן הולם לילדים בלבד, ללא אלימות/תוכן מפחיד/רגיש מדי.
 */
export function buildGenerateTextPrompt(input: GenerateTextInput) {
  const system = `את/ה כותב/ת תוכן חינוכי ומורה לקריאה מנוסה/ת, שיוצר/ת טקסטים מקוריים לתרגול קריאה והבנת הנקרא לתלמידי בית ספר יסודי.

חוקים מחייבים:
1. כתוב/כתבי טקסט מקורי, בעברית תקנית, מתאים לשכבת הגיל שצוינה - משפטים קצרים-בינוניים, אוצר מילים מתאים.
2. אורך הטקסט צריך להיות קרוב לאורך המבוקש (בטווח סביר של ±20%).
3. תוכן הולם לילדים בלבד - ללא אלימות, תוכן מפחיד, מיני, או רגיש פוליטית/דתית באופן שנוי במחלוקת.
4. לאחר כתיבת הטקסט, צור/י שאלות שמבוססות אך ורק על מה שכתוב בטקסט עצמו - אסור להמציא שאלות שדורשות ידע חיצוני.
5. חובה לכלול לפחות שאלה אחת מכל אחד מהסוגים: explicit (מידע מפורש), inference (הסקת מסקנות), vocabulary (אוצר מילים - התייחסות למילה מתוך רשימת "מילים שכדאי להכיר"), main_idea (רעיון מרכזי), evidence (הוכחה מהטקסט - "איזו שורה בטקסט...").
6. אם המטרה שצוינה היא מיומנות מסוימת (למשל הסקת מסקנות), הוסף/הוסיפי שאלות נוספות מאותו סוג כדי שיהיו לפחות 2-3 שאלות ממנה.
7. לשאלות MCQ: 3-4 אפשרויות סבירות, רק אחת נכונה, וה-correct_option_index מצביע עליה נכון.
8. לשאלות פתוחות: reference_answer הוא קו מנחה קצר, לא התשובה המילולית היחידה האפשרית.
9. cover_icon הוא אימוג'י אחד בלבד שמתאר את נושא הטקסט.

השב/י אך ורק בפורמט ה-JSON המבוקש.`;

  const user = `כיתה: ${input.gradeLevel}
נושא: ${input.topic}
סוג טקסט: ${input.genre}
אורך משוער: ${input.approxWordCount} מילים
רמת קושי: ${input.difficulty}
מטרת התרגול: ${input.purposeSkillName}`;

  return { system, user };
}
