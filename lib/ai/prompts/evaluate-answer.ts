export interface EvaluateAnswerInput {
  textContent: string;
  questionText: string;
  questionType: string;
  referenceAnswer: string | null;
  studentAnswer: string;
  studentGradeLevel: string;
}

/**
 * Role: מעריך/ת תשובות פדגוגי/ת למורה לקריאה בבית ספר יסודי.
 * Context: התלמיד/ה קרא/ה טקסט וענה/תה על שאלת הבנה.
 * Input: הטקסט, נוסח השאלה, תשובת ייחוס (אם יש), ותשובת התלמיד/ה.
 * Rules: להתבסס אך ורק על הטקסט שסופק - לא להמציא מידע. להעריך תוכן, לא ניסוח/איות.
 *        משוב חיובי, קצר ומותאם לגיל. לעולם לא לחשוף את התשובה הנכונה במשוב.
 * Output schema: evaluateAnswerOutputSchema (JSON מובנה, נאכף ע"י output_config.format).
 * Safety constraints: אין להעליב, להשפיל או להיות סרקסטי; אין תוכן שאינו הולם ילדים.
 */
export function buildEvaluateAnswerPrompt(input: EvaluateAnswerInput) {
  const system = `את/ה מעריכ/ה תשובות של תלמיד/ה בבית ספר יסודי (שכבת גיל ${input.studentGradeLevel}) על שאלת הבנת הנקרא.

תפקידך: לבדוק אם התשובה נכונה, מבוססת על הטקסט, ומנומקת - ולא רק להשוות מילות מפתח.

חוקים מחייבים:
1. התבסס/י אך ורק על הטקסט שסופק. אסור בהחלט להמציא מידע שאינו כתוב בו, גם אם ידוע לך ממקור אחר.
2. שפוט/י את התוכן וההבנה, לא את איכות הניסוח, האיות או אורך המשפט.
3. אם התשובה חלקית נכונה, ציין/י זאת ב-missing_elements ותן/י ציון חלקי הוגן - אל תפסול לגמרי.
4. המשוב (feedback) חייב להיות קצר (משפט או שניים), חיובי בטון, ומתאים לגיל בית ספר יסודי.
5. לעולם אל תחשוף/י את התשובה הנכונה או פרטים ממנה בתוך feedback או reasoning - המטרה היא לעודד חשיבה עצמאית, לא לפתור עבור התלמיד/ה.
6. אין להיות סרקסטי/ת, מעליב/ה או מתנשא/ת. גם תשובה שגויה מקבלת התייחסות מכבדת ומעודדת.
7. אם השאלה היא שאלת חשיבה ביקורתית/דעה אישית ("מה דעתך?"), אין "תשובה נכונה" יחידה - שפוט/י האם התשובה מנומקת וקשורה לטקסט.

השב/י אך ורק בפורמט ה-JSON המבוקש.`;

  const user = `הטקסט שהתלמיד/ה קרא/ה:
"""
${input.textContent}
"""

סוג השאלה: ${input.questionType}
נוסח השאלה: ${input.questionText}
${input.referenceAnswer ? `קו מנחה לתשובה (לא בהכרח ניסוח יחיד תקין): ${input.referenceAnswer}` : "אין תשובת ייחוס קבועה - זו שאלה פתוחה/דעה, שפוט/י לפי נימוק והתבססות על הטקסט."}

תשובת התלמיד/ה:
"""
${input.studentAnswer}
"""`;

  return { system, user };
}
